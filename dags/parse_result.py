import json
import os
import tomllib
from pathlib import Path

from airflow.providers.mysql.hooks.mysql import MySqlHook

STEP_NAME = "parse_result"
MAX_RETRIES = 5

# Folder that task 1 writes config_<tid>.toml into
CONFIG_DIR = '/opt/airflow/toml_config_files/'

# kW per panel, used to estimate power_generation. None = not known yet (column stays NULL)
PANEL_KW = None

# -----------------------------------------------------------------------------
# The actual result work for ONE task (shared by pending and retry paths)
# -----------------------------------------------------------------------------

def read_results(tid):
    # Heavy imports live here, so DAG parsing stays fast
    import shapefile # pyshp
    from rasterio.crs import CRS
    from rasterio.warp import transform_geom

    # Retrieves the output folder and job name from the config file generated by task 1
    config_file_path = os.path.join(CONFIG_DIR, f"config_{tid}.toml")

    with open(config_file_path, "rb") as file:
        cfg = tomllib.load(file)["inference"]

    output_folder_path = Path(cfg["inference_path"]) / cfg["output_folder"]

    # A: The AI writes <job_name>-corrected.shp (final polygons) and one merged mask .tif
    # job_name on the advisor's machine is the tid (see run_inference), so match by pattern
    shapefiles = sorted(output_folder_path.glob("*-corrected.shp"))
    if not shapefiles:
        raise FileNotFoundError(f"No *-corrected.shp in '{output_folder_path}'.")
    shapefile_path = shapefiles[0]

    overlay_images = sorted(output_folder_path.glob("*.tif"))
    overlay_image_path = overlay_images[0] if overlay_images else None

    # B: Sum area and panel count over every polygon
    # Fields: size, area, correct, adjusted_a (area after correction), no_panel, average_pa
    surface_area = 0.0
    panel_total = 0.0
    features = []

    src_crs = CRS.from_wkt(shapefile_path.with_suffix(".prj").read_text())

    with shapefile.Reader(str(shapefile_path)) as reader:
        for shape_record in reader.iterShapeRecords():
            record = shape_record.record.as_dict()
            surface_area += float(record["adjusted_a"])
            panel_total += float(record["no_panel"])

            # Reproject each polygon to WGS84 (lat/lng) so the web map can draw it
            geometry = transform_geom(src_crs, "EPSG:4326", shape_record.shape.__geo_interface__)
            features.append({"type": "Feature", "geometry": geometry, "properties": record})

    # C: Write a GeoJSON next to the shapefile for the web map
    geojson_path = shapefile_path.with_suffix(".geojson")
    with open(geojson_path, "w", encoding="utf-8") as file:
        json.dump({"type": "FeatureCollection", "features": features}, file)

    panel_count = round(panel_total)
    power_generation = panel_count * PANEL_KW if PANEL_KW is not None else None

    return {
        "surface_area": round(surface_area, 2),
        "power_generation": power_generation,
        "panel_count": panel_count,
        "overlay_image_path": str(overlay_image_path) if overlay_image_path else None,
        "shapefile_path": str(shapefile_path),
        "n_polygons": len(features),
    }

# -----------------------------------------------------------------------------
# Status bookkeeping for ONE task
# -----------------------------------------------------------------------------

def process_task(connection, cursor, task):
    tid = task['tid']

    try:
        # Mark Task_Step and Task as running
        cursor.execute(
            """
            UPDATE task_step
            SET status = 'running', started_at = CURRENT_TIMESTAMP
            WHERE tid = %s AND step_name = %s;
            """,
            (tid, STEP_NAME),
        )
        cursor.execute(
            """
            UPDATE task
            SET status = 'parse_result:running'
            WHERE tid = %s;
            """,
            (tid,),
        )

        result = read_results(tid)
        print(f"Parsed {result['n_polygons']} polygons: {result['panel_count']} panels, "
              f"{result['surface_area']} m2")

        # Replace any old result, so a rerun does not leave two rows behind
        cursor.execute("DELETE FROM task_result WHERE tid = %s;", (tid,))
        cursor.execute(
            """
            INSERT INTO task_result
                (tid, surface_area, power_generation, panel_count, overlay_image_path, shapefile_path)
            VALUES (%s, %s, %s, %s, %s, %s);
            """,
            (
                tid,
                result['surface_area'],
                result['power_generation'],
                result['panel_count'],
                result['overlay_image_path'],
                result['shapefile_path'],
            ),
        )

        # Mark Task_Step and Task as completed (this is the last step)
        cursor.execute(
            """
            UPDATE task_step
            SET status = 'completed', completed_at = CURRENT_TIMESTAMP, error_msg = NULL
            WHERE tid = %s AND step_name = %s;
            """,
            (tid, STEP_NAME),
        )
        cursor.execute(
            """
            UPDATE task
            SET status = 'completed'
            WHERE tid = %s;
            """,
            (tid,),
        )

        connection.commit()
        print(f"Task ID {tid} status updated to 'completed'.\n")

        return True

    except Exception as task_err:
        # Throw away the half-done change, then record the failure
        connection.rollback()
        error_message = str(task_err)
        print(f"Failed to parse result for Task ID {tid}: {error_message}")

        cursor.execute(
            """
            UPDATE task_step
            SET status = 'failed', error_msg = %s, completed_at = CURRENT_TIMESTAMP
            WHERE tid = %s AND step_name = %s;
            """,
            (error_message, tid, STEP_NAME),
        )
        cursor.execute(
            """
            UPDATE task
            SET status = 'parse_result:failed'
            WHERE tid = %s;
            """,
            (tid,),
        )

        connection.commit()
        print(f"Task ID {tid} status updated to 'parse_result:failed'.\n")

        return False

# -----------------------------------------------------------------------------
# Entry point called by the Airflow task
# -----------------------------------------------------------------------------

def parse_result_file():
    mysql_hook = MySqlHook(mysql_conn_id='solar_mysql')
    connection = None
    cursor = None

    try:
        connection = mysql_hook.get_conn()
        cursor = connection.cursor() # dict cursor comes from the connection's Extra

        select_sql = """
            SELECT tid, title
            FROM task
            WHERE status = %s;
        """

        # 1. Fetch tasks waiting for result parsing
        cursor.execute(select_sql, ('parse_result:pending',))
        pending_tasks = cursor.fetchall()

        cursor.execute(select_sql, ('parse_result:failed',))
        failed_tasks = cursor.fetchall()

        if not (pending_tasks or failed_tasks):
            print(f"No tasks currently waiting for parsing results.")
            return

        # 2.1 Pending tasks
        if pending_tasks:
            for task in pending_tasks:
                print(f"Processing Task ID: {task['tid']}")
                print(f"Processing Task Title: {task['title']}")
                process_task(connection, cursor, task)

        # 2.2 Failed tasks (retry up to MAX_RETRIES times)
        if failed_tasks:
            for task in failed_tasks:
                tid = task['tid']
                title = task['title']
                print(f"Verifying retriability of Task ID: {tid}")
                print(f"Verifying retriability of Task Title: {title}")

                cursor.execute(
                    """
                    SELECT retry_count
                    FROM task_step
                    WHERE tid = %s AND step_name = %s;
                    """,
                    (tid, STEP_NAME),
                )
                retry_num = cursor.fetchone()

                if retry_num and retry_num['retry_count'] >= MAX_RETRIES:
                    print(f"Task ID {tid} reached the retry limit, skipping.\n")
                    continue

                print(f"Retrying Task ID {tid}")
                print(f"Retrying Task Title {title}")

                # Commit the increment right away so a later rollback cannot undo it
                cursor.execute(
                    """
                    UPDATE task_step
                    SET retry_count = retry_count + 1
                    WHERE tid = %s AND step_name = %s;
                    """,
                    (tid, STEP_NAME),
                )
                connection.commit()

                process_task(connection, cursor, task)

    except Exception as ex:
        if connection:
            connection.rollback()
        print(f"Execution error: {ex}")
        raise
    finally:
        if cursor:
            cursor.close()
        if connection:
            connection.close()
